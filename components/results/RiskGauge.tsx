"use client";

import React from "react";
import { RiskClassification } from "@/lib/types";
import { AlertTriangle, CheckCircle, ShieldAlert } from "lucide-react";

interface RiskGaugeProps {
  percentage: number;
  probability: number;
  classification: RiskClassification;
}

export function RiskGauge({ percentage, probability, classification }: RiskGaugeProps) {
  // Theme color mapping
  const isHigh = classification.level === "Higher";
  const isIntermediate = classification.level === "Intermediate";
  const isLow = classification.level === "Lower";

  const ringColor = isHigh
    ? "text-rose-600"
    : isIntermediate
    ? "text-amber-500"
    : "text-emerald-500";

  const badgeBg = isHigh
    ? "bg-rose-50 text-rose-800 border-rose-200"
    : isIntermediate
    ? "bg-amber-50 text-amber-800 border-amber-200"
    : "bg-emerald-50 text-emerald-800 border-emerald-200";

  // SVG Gauge calculations
  const radius = 80;
  const stroke = 12;
  const normalizedRadius = radius - stroke * 2;
  const circumference = normalizedRadius * 2 * Math.PI;
  const strokeDashoffset = circumference - (percentage / 100) * circumference;

  return (
    <div className="bg-white rounded-2xl border border-slate-200 shadow-sm p-6 sm:p-8 flex flex-col md:flex-row items-center gap-8">
      {/* Gauge Visualization */}
      <div className="relative flex-shrink-0 flex items-center justify-center">
        <svg height={radius * 2} width={radius * 2} className="rotate-[-90deg]">
          <circle
            stroke="#e2e8f0"
            fill="transparent"
            strokeWidth={stroke}
            r={normalizedRadius}
            cx={radius}
            cy={radius}
          />
          <circle
            className={`transition-all duration-1000 ease-out ${ringColor}`}
            stroke="currentColor"
            fill="transparent"
            strokeWidth={stroke}
            strokeDasharray={circumference + " " + circumference}
            style={{ strokeDashoffset }}
            strokeLinecap="round"
            r={normalizedRadius}
            cx={radius}
            cy={radius}
          />
        </svg>

        <div className="absolute flex flex-col items-center justify-center text-center px-1">
          <span className="text-3xl sm:text-4xl font-black text-slate-900 tracking-tight">
            {percentage}%
          </span>
          <span className="text-[10px] font-semibold text-slate-500 uppercase tracking-wider leading-tight">
            Model-Estimated<br />Probability
          </span>
        </div>
      </div>

      {/* Description & Classification */}
      <div className="space-y-3 flex-1 text-center md:text-left">
        <div className="flex flex-wrap items-center justify-center md:justify-start gap-2">
          <span className={`inline-flex items-center gap-1.5 px-3 py-1 rounded-full text-xs font-bold border ${badgeBg}`}>
            {isHigh && <ShieldAlert className="w-3.5 h-3.5" />}
            {isIntermediate && <AlertTriangle className="w-3.5 h-3.5" />}
            {isLow && <CheckCircle className="w-3.5 h-3.5" />}
            <span>{classification.title}</span>
          </span>
          <span className="text-xs text-slate-400 font-mono">P = {probability.toFixed(3)}</span>
        </div>

        <h3 className="text-xl sm:text-2xl font-bold text-slate-900">
          Estimated Risk: <span className={ringColor}>{classification.level}</span>
        </h3>

        <p className="text-sm text-slate-600 leading-relaxed max-w-xl">
          {classification.summary}
        </p>

        <div className="pt-2 text-xs text-slate-500 bg-slate-50 p-3 rounded-xl border border-slate-200">
          <strong>Application-Defined Screening Categories:</strong> These categories (Lower &lt; 35%, Intermediate 35–65%, Higher &gt; 65%) are application-defined screening thresholds for educational demonstration and are not official clinical diagnostic cutoffs. This result is generated by a machine learning model and should not be interpreted as a medical diagnosis.
        </div>
      </div>
    </div>
  );
}
